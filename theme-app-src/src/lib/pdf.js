// A tiny one-page PDF writer (Helvetica, text only) so "Download PDF" gives a
// real file in the prototype without pulling in a PDF library.
const esc = (s) => String(s).replace(/[\\()]/g, (c) => `\\${c}`).replace(/[^\x20-\x7e]/g, (c) => ({ '—': '-', '–': '-', '·': '-', '’': "'", '“': '"', '”': '"', '→': '->' }[c] || ''));

/**
 * lines: [{ text, size?, bold?, gap?, color? }] laid out top to bottom.
 * rows: optional [label, value] pairs drawn as a two-column list.
 */
export function makePdf({ title, sub, rows = [], paras = [] }) {
  const ops = [];
  let y = 790;
  const text = (s, x, size = 10, bold = false, grey = false) => { ops.push(`BT ${grey ? '0.45 g' : '0.1 g'} /${bold ? 'F2' : 'F1'} ${size} Tf ${x} ${y} Td (${esc(s)}) Tj ET`); };
  ops.push('0.08 0.42 0.22 rg 40 812 515 4 re f');
  text(title, 40, 17, true); y -= 20;
  if (sub) { text(sub, 40, 10, false, true); y -= 14; }
  y -= 12;
  rows.forEach(([k, v]) => { text(k, 40, 10, false, true); text(v ?? '-', 210, 10, true); y -= 20; });
  paras.forEach(({ head, body }) => {
    y -= 10; text(head, 40, 12, true); y -= 16;
    wrap(body, 92).forEach((l) => { text(l, 40, 10); y -= 14; });
  });
  y = 40; text(`Generated by Munafasat on ${new Date().toLocaleDateString('en-GB')}`, 40, 8, false, true);
  const stream = ops.join('\n');
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
  ];
  let out = '%PDF-1.4\n';
  const offs = objs.map((o, i) => { const at = out.length; out += `${i + 1} 0 obj\n${o}\nendobj\n`; return at; });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offs.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
  out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([out], { type: 'application/pdf' });
}

function wrap(s, n) {
  const words = String(s).split(/\s+/); const lines = []; let cur = '';
  words.forEach((w) => { if ((cur + ' ' + w).trim().length > n) { lines.push(cur); cur = w; } else cur = (cur + ' ' + w).trim(); });
  if (cur) lines.push(cur);
  return lines;
}

export function downloadPdf(name, spec) {
  const url = URL.createObjectURL(makePdf(spec));
  const a = document.createElement('a'); a.href = url; a.download = `${name.replace(/[^\w.-]+/g, '-')}.pdf`;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
